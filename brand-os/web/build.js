#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// web/build.js — build the static (Vercel) edition of the console.
//
//   node brand-os/web/build.js      → brand-os/web/site/
//
// Output directory is `web/site` (not `dist`): `dist` is excluded from workspace
// snapshots, and Vercel's outputDirectory points here.
//
// What it does:
//   1. bundles lib/*.js into dist/bb-lib.js with a 20-line CommonJS shim
//   2. copies public/{index.html,style.css,app.js}
//   3. writes dist/boot.js — the browser "server" (browser-api.js) + a
//      first-run seed, so the deployed site has data on first paint
//
// The static build uses exactly the same engine, agents, orchestrator and
// actions as the Node server. Only the storage and transport differ:
// localStorage instead of data/state.json, fetch shim instead of HTTP.
// ─────────────────────────────────────────────────────────────────────────────
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const LIB = path.join(ROOT, 'lib');
const PUBLIC = path.join(ROOT, 'public');
const OUT = path.join(__dirname, 'site');

const MODULES = ['playbook', 'state', 'engine', 'agents', 'orchestrator', 'actions', 'kit'];

function moduleSource(name) {
  let src = fs.readFileSync(path.join(LIB, `${name}.js`), 'utf8');
  // Node-only headers are harmless once wrapped, but the comments confuse readers.
  return src;
}

function bundle() {
  const defs = MODULES.map(name => `__def(${JSON.stringify(name)}, function (module, exports, require) {\n${moduleSource(name)}\n});`).join('\n\n');

  return `/* Buyable Brand OS — browser bundle. Generated by web/build.js. Do not edit. */
(function () {
  var __mods = {}, __cache = {};
  function __def(name, factory) { __mods[name] = factory; }
  function require(name) {
    var key = String(name).replace(/^\\.\\//, '').replace(/\\.js$/, '');
    if (key === 'zlib' || key === 'fs' || key === 'path') throw new Error('Node module not available in the browser: ' + key);
    if (__cache[key]) return __cache[key].exports;
    if (!__mods[key]) throw new Error('Unknown module: ' + name);
    var m = { exports: {} };
    __cache[key] = m;
    __mods[key](m, m.exports, require);
    return m.exports;
  }

${defs}

  window.BB = {
    playbook: require('playbook'),
    state: require('state'),
    engine: require('engine'),
    agents: require('agents'),
    orchestrator: require('orchestrator'),
    actions: require('actions'),
    kit: require('kit'),
  };
})();
`;
}

const boot = `/* seeded on first visit, then the browser owns its own data */
(function () {
  var KEY = 'bb.static.state.v1';
  try {
    if (!window.localStorage.getItem(KEY)) {
      var today = window.BB.engine.todayStr();
      window.localStorage.setItem(KEY, JSON.stringify(window.BB.state.freshState(today)));
    }
  } catch (e) { /* storage blocked: the API keeps state in memory */ }
})();
`;

function banner() {
  return `
(function () {
  // say out loud where the data lives — this build has no server
  function chip() {
    var host = document.getElementById('goalChip');
    if (!host || document.getElementById('staticChip')) return;
    var c = document.createElement('span');
    c.id = 'staticChip';
    c.className = 'chip';
    c.title = 'Static build: state is saved in this browser (localStorage), not on a server. Use Export to move it.';
    c.textContent = 'local data';
    host.parentNode.insertBefore(c, host.nextSibling);
  }
  window.addEventListener('bb:error', function (e) {
    if (window.toast) window.toast(e.detail || 'Something failed', true);
  });
  var t = setInterval(function () {
    if (document.querySelector('#nav a')) { chip(); clearInterval(t); }
  }, 200);
  setTimeout(function () { clearInterval(t); }, 8000);
})();
`;
}

function main() {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });

  fs.writeFileSync(path.join(OUT, 'bb-lib.js'), bundle(), 'utf8');
  fs.copyFileSync(path.join(PUBLIC, 'style.css'), path.join(OUT, 'style.css'));
  fs.copyFileSync(path.join(PUBLIC, 'app.js'), path.join(OUT, 'app.js'));

  // index.html: same shell, plus the bundle + browser API before app.js
  let html = fs.readFileSync(path.join(PUBLIC, 'index.html'), 'utf8');
  html = html.replace('<script src="app.js"></script>',
    `<script src="bb-lib.js"></script>
<script src="browser-api.js"></script>
<script src="boot.js"></script>
<script src="app.js"></script>`);
  html = html.replace('<!--SHELL-->', '');
  fs.writeFileSync(path.join(OUT, 'index.html'), html, 'utf8');

  fs.copyFileSync(path.join(__dirname, 'browser-api.js'), path.join(OUT, 'browser-api.js'));
  fs.writeFileSync(path.join(OUT, 'boot.js'), boot + banner(), 'utf8');

  const sizes = fs.readdirSync(OUT).map(f => {
    const bytes = fs.statSync(path.join(OUT, f)).size;
    return `${f.padEnd(16)} ${(bytes / 1024).toFixed(1)}kB`;
  });
  console.log(`built ${OUT}`);
  for (const line of sizes) console.log('  ' + line);
  console.log(`  total            ${(fs.readdirSync(OUT).reduce((t, f) => t + fs.statSync(path.join(OUT, f)).size, 0) / 1024).toFixed(1)}kB`);
}

main();
